package com.neighbor.eventmosaic.search.api;

/**
 * Строит один актуальный снимок событий для окраски опубликованной карты стран.
 * Границы времени выбирает сервер, поэтому вызывающей стороне не нужно передавать
 * период или параметры пространственного отбора.
 */
public interface CountryMapSnapshotQuery {

	/**
	 * Читает плотный снимок для текущего закрытого суточного окна.
	 *
	 * @return снимок со всеми регионами каталога и оценкой полноты данных
	 * @throws SearchAccessException если поисковая модель недоступна или вернула
	 *                               внутренне противоречивые счетчики
	 */
	CountryMapSnapshot read();
}
