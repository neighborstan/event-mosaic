package com.neighbor.eventmosaic.ingestion.trigger;

/**
 * Определяет единственный способ запуска загрузки GDELT в текущем процессе.
 * Режим нужен точке сборки приложения, чтобы создать только подходящий
 * механизм запуска.
 */
public enum IngestionRuntimeMode {
	/** Обычное веб-приложение последовательно планирует циклы загрузки. */
	AUTOMATIC,

	/** Явная команда выполняет ровно один цикл загрузки. */
	ONE_SHOT,

	/** Процесс не запускает загрузку или служебную операцию. */
	DISABLED,

	/** Процесс выполняет одну явно выбранную служебную команду без веб-сервера. */
	MAINTENANCE
}
